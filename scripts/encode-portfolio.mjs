/**
 * Reads portfolio.private.json (plaintext, gitignored) and writes
 * src/data/portfolio.generated.ts with XOR+Base64 obfuscated fields.
 *
 * Usage:
 *   1. Copy portfolio.private.example.json → portfolio.private.json
 *   2. Edit portfolio.private.json with your real details
 *   3. npm run encode:portfolio
 *   4. Commit only the generated .ts file (never the .json)
 */

import { readFileSync, writeFileSync, existsSync, copyFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const privatePath = join(root, 'portfolio.private.json')
const examplePath = join(root, 'portfolio.private.example.json')
const outPath = join(root, 'src', 'data', 'portfolio.generated.ts')

const KEY = 'slim08-portfolio-v1'

function encode(plain) {
  const bytes = Buffer.from(String(plain), 'utf8')
  const key = Buffer.from(KEY, 'utf8')
  const out = Buffer.alloc(bytes.length)
  for (let i = 0; i < bytes.length; i++) {
    out[i] = bytes[i] ^ key[i % key.length]
  }
  return out.toString('base64')
}

function o(plain) {
  return `o('${encode(plain)}')`
}

function assertString(value, path) {
  if (typeof value !== 'string' || value.length === 0) {
    throw new Error(`Expected non-empty string at ${path}`)
  }
}

function encodeCoding(project, index) {
  const base = `codingProjects[${index}]`
  assertString(project.id, `${base}.id`)
  assertString(project.name, `${base}.name`)
  assertString(project.description, `${base}.description`)
  if (!Array.isArray(project.achievements)) {
    throw new Error(`Expected array at ${base}.achievements`)
  }
  if (!Array.isArray(project.screenshots)) {
    throw new Error(`Expected array at ${base}.screenshots`)
  }

  const achievements = project.achievements
    .map((row, i) => {
      assertString(row.built, `${base}.achievements[${i}].built`)
      assertString(row.because, `${base}.achievements[${i}].because`)
      return `      { built: ${o(row.built)}, because: ${o(row.because)} },`
    })
    .join('\n')

  const screenshots = project.screenshots
    .map((src, i) => {
      assertString(src, `${base}.screenshots[${i}]`)
      return `    ${o(src)},`
    })
    .join('\n')

  return `  {
    id: ${JSON.stringify(project.id)},
    kind: 'coding',
    name: ${o(project.name)},
    description: ${o(project.description)},
    achievements: [
${achievements}
    ],
    screenshots: [
${screenshots}
    ],
  },`
}

function encodeMusic(project, index) {
  const base = `musicProjects[${index}]`
  assertString(project.id, `${base}.id`)
  assertString(project.name, `${base}.name`)
  assertString(project.description, `${base}.description`)
  assertString(project.audioFile, `${base}.audioFile`)
  if (!Array.isArray(project.designChoices)) {
    throw new Error(`Expected array at ${base}.designChoices`)
  }

  const designChoices = project.designChoices
    .map((row, i) => {
      assertString(row.choice, `${base}.designChoices[${i}].choice`)
      assertString(row.because, `${base}.designChoices[${i}].because`)
      return `      { choice: ${o(row.choice)}, because: ${o(row.because)} },`
    })
    .join('\n')

  return `  {
    id: ${JSON.stringify(project.id)},
    kind: 'music',
    name: ${o(project.name)},
    description: ${o(project.description)},
    designChoices: [
${designChoices}
    ],
    audioFile: ${o(project.audioFile)},
  },`
}

if (!existsSync(privatePath)) {
  if (!existsSync(examplePath)) {
    console.error('Missing portfolio.private.json and portfolio.private.example.json')
    process.exit(1)
  }
  copyFileSync(examplePath, privatePath)
  console.log('Created portfolio.private.json from example (edit this file; it is gitignored).')
}

const raw = JSON.parse(readFileSync(privatePath, 'utf8'))
if (!Array.isArray(raw.codingProjects) || !Array.isArray(raw.musicProjects)) {
  throw new Error('JSON must include codingProjects and musicProjects arrays')
}

const codingBlock = raw.codingProjects.map(encodeCoding).join('\n')
const musicBlock = raw.musicProjects.map(encodeMusic).join('\n')

const file = `/**
 * AUTO-GENERATED by scripts/encode-portfolio.mjs — do not edit by hand.
 * Source: portfolio.private.json (gitignored plaintext)
 * Regenerate: npm run encode:portfolio
 */

import { o } from './obfuscate'

export const codingProjects = [
${codingBlock}
]

export const musicProjects = [
${musicBlock}
]
`

writeFileSync(outPath, file, 'utf8')
console.log(`Wrote ${outPath}`)
console.log(
  `Encoded ${raw.codingProjects.length} coding + ${raw.musicProjects.length} music projects.`,
)
